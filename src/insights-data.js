export function findInsight(path) {
  return insightArticles.find((a) => path === `/insights/${a.slug}`);
}
export function readingMinutes(article) {
  const text = [
    article.summary,
    article.takeaway,
    ...article.sections.flatMap(([, title, body, list = []]) => [
      title,
      body,
      ...list,
    ]),
    ...article.checklist,
  ].join(" ");
  return Math.max(2, Math.ceil(text.split(/\s+/).length / 200));
}
